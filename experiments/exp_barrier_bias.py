"""Stage 3: resolve discrete barrier-monitoring bias with control variates.

The up-and-in call is simulated at 12, 52 and 252 monitoring dates.  Its mean
is compared with the continuous Reiner--Rubinstein value and the BGK
continuity correction at the same monitoring frequency.

Usage
-----
    python experiments/exp_barrier_bias.py
    python experiments/exp_barrier_bias.py --analyze-only
"""

import os

os.environ.setdefault("OMP_NUM_THREADS", "1")

import argparse
import json
import math
import sys
from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd
from scipy.stats import t

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.benchmark import exact_price, exact_price_bgk, run_sweep
from src.config import R, SCENARIOS
from src.plots import METHOD_COLORS, apply_style, save_fig
from src.results import _RESULTS_DIR, load_all_results
from src.vr_control import control_variate_mc  # noqa: F401; registers estimator

PERSON = "aritra"
EXPERIMENT_ID = "barrier_bias"
N_PATHS = 65_536
STEP_GRID = [12, 52, 252]
TABLES_DIR = Path(__file__).resolve().parent.parent / "results" / "tables"


def simulate():
    output = _RESULTS_DIR / f"{PERSON}_{EXPERIMENT_ID}.csv"
    output.unlink(missing_ok=True)
    for n_steps in STEP_GRID:
        run_sweep(
            person=PERSON,
            experiment_id=EXPERIMENT_ID,
            cases=[("paper_barrier", "call")],
            methods=["control_variate"],
            n_grid=[N_PATHS],
            R=R,
            n_steps=n_steps,
            schemes=["exact"],
        )


def load_results():
    df = load_all_results()
    df = df[(df["person"] == PERSON) & (df["experiment_id"] == EXPERIMENT_ID)].copy()
    if df.empty:
        raise RuntimeError("No Stage-3 barrier-bias results found; run simulation first.")
    return df


def build_summary(df):
    scenario = SCENARIOS["paper_barrier"]
    continuous = exact_price(scenario, "call")
    rows = []
    for n_steps, group in df.groupby("n_steps"):
        if len(group) != R:
            raise RuntimeError(f"Expected {R} rows at n_steps={n_steps}, found {len(group)}")
        extras = [json.loads(value) for value in group["extra_json"]]
        mean_price = group["price"].mean()
        mean_se = group["price"].std(ddof=1) / math.sqrt(len(group))
        bgk = exact_price_bgk(scenario, "call", int(n_steps))
        rows.append({
            "n_steps": int(n_steps),
            "n_paths": N_PATHS,
            "n_reps": len(group),
            "mean_price": mean_price,
            "mean_price_se": mean_se,
            "mean_reported_cv_se": group["std_error"].mean(),
            "mean_implied_plain_se": sum(x["plain_std_error"] for x in extras) / len(extras),
            "continuous_price": continuous,
            "observed_bias_vs_continuous": mean_price - continuous,
            "bgk_price": bgk,
            "bgk_bias_vs_continuous": bgk - continuous,
            "mc_minus_bgk": mean_price - bgk,
            "rho": sum(x["rho"] for x in extras) / len(extras),
            "b_hat": sum(x["b_hat"] for x in extras) / len(extras),
            "observed_within_vrf": sum(x["observed_vrf"] for x in extras) / len(extras),
        })
    summary = pd.DataFrame(rows).sort_values("n_steps")
    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    summary.to_csv(TABLES_DIR / "barrier_bias_summary.csv", index=False)
    return summary


def make_figure(summary):
    apply_style()
    fig, ax = plt.subplots(figsize=(6.4, 4.4))
    critical = t.ppf(0.975, summary["n_reps"].iloc[0] - 1)
    ax.errorbar(
        summary["n_steps"],
        summary["observed_bias_vs_continuous"],
        yerr=critical * summary["mean_price_se"],
        fmt="o-",
        capsize=4,
        color=METHOD_COLORS["control_variate"],
        label="Control-variate MC (95% CI)",
    )
    ax.plot(
        summary["n_steps"],
        summary["bgk_bias_vs_continuous"],
        "s--",
        color="#333333",
        label="BGK continuity correction",
    )
    ax.axhline(0.0, color="black", linewidth=1, linestyle=":",
               label="Continuous-monitoring limit")
    ax.set_xscale("log")
    ax.set_xticks(STEP_GRID, labels=[str(value) for value in STEP_GRID])
    ax.set_xlabel("Monitoring dates per year")
    ax.set_ylabel("Price bias vs continuous barrier")
    ax.set_title("Discrete monitoring bias becomes visible after variance reduction")
    ax.legend(fontsize=8)
    save_fig(fig, "barrier_bias_vs_steps.png")
    plt.close(fig)


def write_findings(summary):
    lines = [
        "# Stage 3 barrier-monitoring bias",
        "",
        "Generated by `experiments/exp_barrier_bias.py` from "
        "`results/raw/aritra_barrier_bias.csv`.",
        "",
        "| Steps | CV price | bias vs continuous | BGK price | MC - BGK | "
        "CV SE/run | implied plain SE/run | VRF |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for _, row in summary.iterrows():
        lines.append(
            f"| {int(row['n_steps'])} | {row['mean_price']:.6f} | "
            f"{row['observed_bias_vs_continuous']:+.6f} | {row['bgk_price']:.6f} | "
            f"{row['mc_minus_bgk']:+.6f} | {row['mean_reported_cv_se']:.6f} | "
            f"{row['mean_implied_plain_se']:.6f} | {row['observed_within_vrf']:.1f} |"
        )
    row252 = summary[summary["n_steps"] == 252].iloc[0]
    z = abs(row252["observed_bias_vs_continuous"]) / row252["mean_price_se"]
    lines += [
        "",
        f"At 252 dates the measured bias is {row252['observed_bias_vs_continuous']:+.6f}, "
        f"resolved at {z:.1f} standard errors of the replicated mean. A single plain-MC "
        f"run at the same N has an implied SE of {row252['mean_implied_plain_se']:.4f}, "
        "so it cannot expose this bias. The BGK value is the relevant discrete-monitoring "
        "benchmark, while the continuous formula remains the limiting value.",
        "",
    ]
    text = "\n".join(lines)
    (TABLES_DIR / "barrier_bias_findings.md").write_text(text, encoding="utf-8")
    print(text)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--analyze-only", action="store_true")
    args = parser.parse_args()
    if not args.analyze_only:
        simulate()
    df = load_results()
    summary = build_summary(df)
    make_figure(summary)
    write_findings(summary)
    print("Barrier-bias experiment complete.")


if __name__ == "__main__":
    main()
